import { screen, waitFor, within } from "@testing-library/react";
import LZString from "lz-string";
import { useContext } from "react";
import { useLocation } from "react-router-dom";
import { ShareDialog } from "../../components/tasks/ShareDialog";
import { UserContext } from "../../contexts/UserContext";
import { renderWithProviders } from "../../test/renderWithProviders";
import type { Task } from "../../types/user";
import SharePage from "../Share";

const sharedTask = {
  done: false,
  pinned: false,
  name: "Buy groceries",
  description: "Milk and eggs",
  emoji: "1f6d2",
  color: "#00aa55",
  date: "2025-01-02T10:00:00.000Z",
};

const compress = (value: unknown) => LZString.compressToEncodedURIComponent(JSON.stringify(value));

const shareRoute = (task: string | null, userName: string | null = "Ada") => {
  const params = new URLSearchParams();
  if (task !== null) params.set("task", task);
  if (userName !== null) params.set("userName", userName);
  return `/share?${params.toString()}`;
};

// Exposes the router location and the stored tasks next to the page.
function Probe() {
  const { pathname } = useLocation();
  const { user } = useContext(UserContext);
  return (
    <>
      <span data-testid="path">{pathname}</span>
      <span data-testid="task-names">{user.tasks.map((t) => t.name).join(",")}</span>
      <span data-testid="task-sender">{user.tasks.map((t) => t.sharedBy).join(",")}</span>
    </>
  );
}

const renderShare = (route: string) =>
  renderWithProviders(
    <>
      <SharePage />
      <Probe />
    </>,
    { route },
  );

const dialog = () => screen.findByRole("dialog");

describe("SharePage", () => {
  beforeEach(() => {
    vi.spyOn(console, "error").mockImplementation(() => {});
  });

  afterEach(() => {
    vi.restoreAllMocks();
  });

  it("shows the shared task and who sent it", async () => {
    renderShare(shareRoute(compress(sharedTask)));

    const view = within(await dialog());
    expect(await view.findByText("Recieved Task")).toBeInTheDocument();
    expect(view.getByText("Ada")).toBeInTheDocument();
    expect(view.getByText("Buy groceries")).toBeInTheDocument();
    expect(view.getByRole("button", { name: /add task/i })).toBeInTheDocument();
    expect(document.title).toBe("Todo App - Recieved Task (Buy groceries)");
  });

  it("accepts the legacy uncompressed JSON format", async () => {
    renderShare(shareRoute(JSON.stringify(sharedTask)));

    const view = within(await dialog());
    expect(await view.findByText("Buy groceries")).toBeInTheDocument();
  });

  it("adds the shared task to the user's list and returns home", async () => {
    const { user } = renderShare(shareRoute(compress(sharedTask)));

    await user.click(await within(await dialog()).findByRole("button", { name: /add task/i }));

    await waitFor(() => expect(screen.getByTestId("path")).toHaveTextContent("/"));
    expect(screen.getByTestId("task-names")).toHaveTextContent("Buy groceries");
    expect(screen.getByTestId("task-sender")).toHaveTextContent("Ada");
  });

  it("does not add the task when it is declined", async () => {
    const { user } = renderShare(shareRoute(compress(sharedTask)));

    await user.click(await within(await dialog()).findByRole("button", { name: /decline/i }));

    expect(screen.getByTestId("path").textContent).toBe("/");
    expect(screen.getByTestId("task-names")).toBeEmptyDOMElement();
  });

  it("opens a link generated by the share dialog", async () => {
    const task: Task = {
      id: "11111111-1111-4111-8111-111111111111",
      ...sharedTask,
      date: new Date(sharedTask.date),
    };
    const { unmount } = renderWithProviders(
      <ShareDialog open onClose={vi.fn()} selectedTask={task} />,
      { initialUser: { name: "Grace" } },
    );
    const link = (screen.getByLabelText("Shareable Link") as HTMLInputElement).value;
    unmount();

    const url = new URL(link);
    renderShare(url.pathname + url.search);

    const view = within(await dialog());
    expect(await view.findByText("Buy groceries")).toBeInTheDocument();
    expect(view.getByText("Grace")).toBeInTheDocument();
  });

  describe("invalid links", () => {
    const expectError = async (details: RegExp | string) => {
      const view = within(await dialog());
      expect(await view.findByText("Failed to recieve Task")).toBeInTheDocument();
      expect(view.getByText(details)).toBeInTheDocument();
      expect(view.queryByRole("button", { name: /add task/i })).not.toBeInTheDocument();
    };

    it("reports a missing task parameter", async () => {
      renderShare(shareRoute(null));

      await expectError("No task data found in the link.");
    });

    it("reports a corrupted compressed payload", async () => {
      renderShare(shareRoute("not-a-valid-payload!!"));

      await expectError(/Failed to decode task data/);
    });

    it("reports a payload that decompresses to invalid JSON", async () => {
      renderShare(shareRoute(LZString.compressToEncodedURIComponent("not json")));

      await expectError(/Failed to decode task data/);
    });

    it("reports malformed legacy JSON", async () => {
      renderShare(shareRoute("{broken"));

      await expectError(/Failed to decode task data/);
    });

    it("rejects a task with an invalid color", async () => {
      renderShare(shareRoute(compress({ ...sharedTask, color: "red" })));

      await expectError("Invalid task or category color format.");
    });

    it("rejects a task with an invalid category color", async () => {
      const category = [{ id: "c1", name: "Work", emoji: "1f4bc", color: "blue" }];
      renderShare(shareRoute(compress({ ...sharedTask, category })));

      await expectError("Invalid task or category color format.");
    });

    it("rejects a sender name that is too long", async () => {
      renderShare(shareRoute(compress(sharedTask), "x".repeat(500)));

      await expectError("User name is too long.");
    });
  });
});
